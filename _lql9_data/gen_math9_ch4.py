checks.append(("相似比2:3→面积比", round((2/3)**2, 6), round(4/9, 6)))
checks.append(("面积比9:4→相似比", round(math.sqrt(9/4), 6), 1.5))
checks.append(("小周长12→大周长", round(12*(3/2), 6), 18.0))
checks.append(("平行线EF=4×3/2", 4*3/2, 6))
checks.append(("楼高=1.5×6/0.5", 1.5*6/0.5, 18.0))
checks.append(("黄金比(√5−1)/2", round((math.sqrt(5)-1)/2, 6), round(0.618034, 6)))
for name, got, want in checks:
    assert abs(got - want) < 1e-6, f"{name}: got {got} want {want}"
print("数值硬性校验全部通过:", [c[0] for c in checks])

